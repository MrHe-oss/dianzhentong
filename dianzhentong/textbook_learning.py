def lesson_for_topic(topic_id: str) -> dict[str, Any] | None:
    return TEXTBOOK_LESSONS.get(topic_id)


def validate_textbook_lessons() -> None:
    if set(TEXTBOOK_LESSONS) != set(SAMPLE_UNIT_TOPIC_IDS):
        raise ValueError("样板单元小课与知识点不一致")
    required = {"minutes", "lead", "points", "example", "question", "options", "answer", "explanation"}
    for topic_id, lesson in TEXTBOOK_LESSONS.items():
        if not required <= set(lesson) or lesson["answer"] not in lesson["options"]:
            raise ValueError(f"教材小课结构无效：{topic_id}")


validate_textbook_lessons()
