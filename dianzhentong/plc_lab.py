def logic_output(operator, a, b=False):
    if operator == "AND":
        return bool(a and b)
    if operator == "OR":
        return bool(a or b)
    if operator == "NOT":
        return not a
    raise ValueError("未知逻辑")


def hold_next(allow, stop, start, previous):
    return bool(allow and not stop and (start or previous))


@dataclass
class ScanModel:
    phase: int = 0
    sampled: bool = False
    computed: bool = False
    output: bool = False
    cycles: int = 0

    def step(self, live_input):
        if self.phase == 0:
            self.sampled = bool(live_input)
        elif self.phase == 1:
            self.computed = self.sampled
        else:
            self.output = self.computed
            self.cycles += 1
        self.phase = (self.phase + 1) % 3


